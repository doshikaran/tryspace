"""Cross-runtime parity fixture for the rule-based interpreter (decision D12).

The headset runs a C# port of `DeterministicIntentExtractor` + `ProposalService`
(app-unity/.../Content/MovingDay/Scripts/MovingDayLocalProposals.cs). This module writes what the Python
implementation produces for every shared interpretation case, with sequential IDs, so the Unity EditMode suite can
require the C# port to produce the same proposals. It is a parity record, not an independent expectation: expected
values remain the hand-written fields in moving_day_cases.json.

    uv run python -m tryscape_api.creation.parity --write   # regenerate after an intentional interpreter change
"""

from __future__ import annotations

import itertools
import json
import sys
from pathlib import Path
from typing import Any

from tryscape_api.creation import intent as ix
from tryscape_api.creation.proposals import ProposalService

CONTRACTS = Path(__file__).resolve().parents[5] / "contracts" / "v1"
CASES_PATH = CONTRACTS / "fixtures" / "interpretation" / "moving_day_cases.json"
PARITY_PATH = CONTRACTS / "fixtures" / "interpretation" / "moving_day_parity.json"


def sequential_ids() -> Any:
    counter = itertools.count(1)
    return lambda: f"00000000-0000-4000-8000-{next(counter):012d}"


def build() -> dict[str, Any]:
    cases = json.loads(CASES_PATH.read_text())["cases"]
    out = []
    for case in cases:
        proposal = ProposalService(ix.DeterministicIntentExtractor(), sequential_ids()).propose(case["transcript"])
        out.append({"id": case["id"], "proposal": proposal.model_dump(mode="json")})
    return {
        "description": "Python deterministic_rules output for each moving_day_cases.json transcript, IDs "
        "00000000-0000-4000-8000-000000000001 upward in allocation order. Generated by "
        "tryscape_api.creation.parity; the C# port must match it exactly.",
        "provider_id": "deterministic_rules",
        "cases": out,
    }


def render() -> str:
    return json.dumps(build(), indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    if "--write" in argv:
        PARITY_PATH.write_text(render(), encoding="utf-8")
        print(f"wrote {PARITY_PATH}")
        return 0
    current = PARITY_PATH.read_text(encoding="utf-8") if PARITY_PATH.exists() else ""
    if current != render():
        print("parity fixture is stale; run: uv run python -m tryscape_api.creation.parity --write")
        return 1
    print("parity fixture up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
